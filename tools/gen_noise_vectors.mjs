#!/usr/bin/env node
// Generate Dart golden-vector constants from the upstream protocol fixture.
//
// The fixture is the protocol v1 compatibility baseline
// (fixtures/crypto/v1/noise-ik.json in ds-harness-remote, MIT). We never echo
// its contents to stdout: secrets stay inside the generated Dart file only.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..')
const src = resolve(root, 'ref/ds-harness-remote/fixtures/crypto/v1/noise-ik.json')
const out = resolve(root, 'packages/dsh_link/test/vectors/noise_ik_vectors.dart')

const doc = JSON.parse(readFileSync(src, 'utf8'))
const v = doc.vectors[0]

const q = (s) => `'${s}'`

const lines = []
lines.push('// GENERATED FILE - DO NOT EDIT BY HAND.')
lines.push('// Source: ds-harness-remote fixtures/crypto/v1/noise-ik.json (MIT).')
lines.push('// Regenerate with: node tools/gen_noise_vectors.mjs')
lines.push('//')
lines.push('// These are the protocol v1 compatibility baseline. A green test against')
lines.push('// them means our Noise IK wire output is byte-identical to the reference')
lines.push('// implementation, which is what makes us interoperable with real Hosts.')
lines.push('')
lines.push('/// Protocol suite string negotiated by both peers.')
lines.push(`const String kNoiseProtocolSuite = ${q(doc.suite)};`)
lines.push('')
lines.push('/// Fixed protocol version for the vectors above.')
lines.push(`const int kNoiseVectorProtocolVersion = ${doc.protocolVersion};`)
lines.push('')
lines.push('class NoiseVector {')
lines.push('  const NoiseVector({')
lines.push('    required this.name,')
lines.push('    required this.initiatorPrivateKey,')
lines.push('    required this.initiatorPublicKey,')
lines.push('    required this.responderPrivateKey,')
lines.push('    required this.responderPublicKey,')
lines.push('    required this.initiatorEphemeralPrivateKey,')
lines.push('    required this.responderEphemeralPrivateKey,')
lines.push('    required this.prologueConnectionId,')
lines.push('    required this.prologueHostDeviceId,')
lines.push('    required this.prologueClientDeviceId,')
lines.push('    required this.prologueBytes,')
lines.push('    required this.message1Payload,')
lines.push('    required this.message1,')
lines.push('    required this.message2Payload,')
lines.push('    required this.message2,')
lines.push('    required this.transport,')
lines.push('  });')
lines.push('')
lines.push('  final String name;')
lines.push('  final String initiatorPrivateKey;')
lines.push('  final String initiatorPublicKey;')
lines.push('  final String responderPrivateKey;')
lines.push('  final String responderPublicKey;')
lines.push('  final String initiatorEphemeralPrivateKey;')
lines.push('  final String responderEphemeralPrivateKey;')
lines.push('  final String prologueConnectionId;')
lines.push('  final String prologueHostDeviceId;')
lines.push('  final String prologueClientDeviceId;')
lines.push('  final String prologueBytes;')
lines.push('  final String message1Payload;')
lines.push('  final String message1;')
lines.push('  final String message2Payload;')
lines.push('  final String message2;')
lines.push('  final List<NoiseTransportVector> transport;')
lines.push('}')
lines.push('')
lines.push('class NoiseTransportVector {')
lines.push('  const NoiseTransportVector({')
lines.push('    required this.fromInitiator,')
lines.push('    required this.plaintext,')
lines.push('    required this.ciphertext,')
lines.push('  });')
lines.push('')
lines.push('  /// True when the initiator is the sender of this transport message.')
lines.push('  final bool fromInitiator;')
lines.push('  final String plaintext;')
lines.push('  final String ciphertext;')
lines.push('}')
lines.push('')
lines.push('const NoiseVector kNoiseIkVector = NoiseVector(')
lines.push(`  name: ${q(v.name)},`)
lines.push(`  initiatorPrivateKey: ${q(v.staticKeys.initiator.privateKey)},`)
lines.push(`  initiatorPublicKey: ${q(v.staticKeys.initiator.publicKey)},`)
lines.push(`  responderPrivateKey: ${q(v.staticKeys.responder.privateKey)},`)
lines.push(`  responderPublicKey: ${q(v.staticKeys.responder.publicKey)},`)
lines.push(`  initiatorEphemeralPrivateKey: ${q(v.ephemeralPrivateKeys.initiator)},`)
lines.push(`  responderEphemeralPrivateKey: ${q(v.ephemeralPrivateKeys.responder)},`)
lines.push(`  prologueConnectionId: ${q(v.prologue.connectionId)},`)
lines.push(`  prologueHostDeviceId: ${q(v.prologue.hostDeviceId)},`)
lines.push(`  prologueClientDeviceId: ${q(v.prologue.clientDeviceId)},`)
lines.push(`  prologueBytes: ${q(v.prologue.bytes)},`)
lines.push(`  message1Payload: ${q(v.handshake.message1.payload)},`)
lines.push(`  message1: ${q(v.handshake.message1.message)},`)
lines.push(`  message2Payload: ${q(v.handshake.message2.payload)},`)
lines.push(`  message2: ${q(v.handshake.message2.message)},`)
lines.push('  transport: <NoiseTransportVector>[')
for (const t of v.transport) {
  lines.push('    NoiseTransportVector(')
  lines.push(`      fromInitiator: ${t.sender === 'initiator'},`)
  lines.push(`      plaintext: ${q(t.plaintext)},`)
  lines.push(`      ciphertext: ${q(t.ciphertext)},`)
  lines.push('    ),')
}
lines.push('  ],')
lines.push(');')
lines.push('')

mkdirSync(dirname(out), { recursive: true })
writeFileSync(out, lines.join('\n'), 'utf8')
console.log(`wrote ${out} (${lines.length} lines)`)
